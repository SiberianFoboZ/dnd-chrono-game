<p>
  До этого момента любая моя песня действительно получилась бы жалкой. Мне
  просто нечего было сказать людям. Да и чем взять за душу — я и сама не
  понимала. Даже танцы мои были построены на технике: я знала, в какую
  позу встать, как эффектно взмахнуть клинком, как заставить зал задержать
  дыхание. Я вкладывала страсть, но это была страсть эгоистичная: она была
  для меня, чтобы я чувствовала себя сильной, чтобы от меня не могли
  оторвать взгляд. Это была магия тщеславия, а не магия, способная когото
  спасти.
</p>
<p>
  Но сейчас… сейчас всё изменилось. От всей этой ситуации мне хочется
  кричать. Хочется, чтобы весь город кричал вместе со мной. Эта местность
  будто так отчаялась от проклятия, что стала безжизненной, а сердца людей
  покрылись вековой пылью. И впервые в жизни мне хочется не просто
  ослепить их блеском, а поделиться огнём своей души. Разбудить. Вселить
  хоть крошечный луч надежды. Я хочу верить, что мы справимся со Страдом,
  с туманом, с проклятием. Хочу, чтобы в это поверили мои друзья, чтобы
  поверили местные. Пусть эта вера идёт впереди нас, пусть она нас
  поддерживает, даёт силы восстать и противиться злу. Без веры этот мир
  обречён. А я хочу сделать первый шаг к победе — и подарить людям то,
  чего им сейчас больше всего не хватает.
</p>

