<p>
  Слова складывались сами собой, будто ктото шептал их мне на ухо, пока я
  водила пером по бумаге. Пол комнаты был усыпан смятыми листами неудачных
  попыток, но к вечеру мой труд наконецто меня удовлетворил. Глядя на
  исписанный лист, я даже не поверила, что смогла написать это сама. Все
  чувства, которые я прятала, вся злость, вся страсть — они сплелись в
  завитушки букв и легли стройной мелодией на одной странице.
</p>
<p>
  Теперь мне уже не важно, станет ли эта песня лучшей во всём мире. Не
  важно, будут ли меня с кемто сравнивать. Теперь важно лишь одно: чтобы
  мой посыл достиг чьихто сердец. Чтобы ктото, услышав эти слова,
  почувствовал: он не один. Что есть те, кто верит. Что надежда ещё жива.
</p>
<p>
  Ох, стоило мне спуститься, как стало ясно: пока я сражалась с
  собственными демонами и строила мелодии из слов, остальные не теряли
  времени даром. Девушки уже сидели навеселе, болтали без умолку и, судя
  по их раскрасневшимся щекам, успели осушить не по одной кружке местного
  вина — будто пытались залить этой хмельной волной все тревоги минувших
  дней. А тут ещё и Артур вернулся из кузницы со своим новым мечом.
</p>
<p>
  И, право, этот клинок… Он просто неподъёмный! Да, красивый до
  неприличия: тёмная сталь, узор, будто выжженный самой бурей, рукоять,
  оплетённая кожей и чемто ещё, от чего по руке бегут мурашки. Но как
  Артур вообще держит его в руках — ума не приложу. Да, он сильнее меня,
  но не настолько же, чтобы размахивать этой глыбой, словно тростинкой!
</p>

