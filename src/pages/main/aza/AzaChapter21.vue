<p>
  Пожалуй, на сегодня нам действительно хватит сражений и приключений. Мы
  снова собрались все в одной комнате, тесно, плечом к плечу, будто само
  это соседство могло защитить нас от любых бед. Ирина продолжила свои
  попытки расшифровать дневник Страда. Возможно, на него наложена какаято
  магия — иначе как объяснить то, что, читая расшифрованный текст, мы
  будто сами переносимся в те события, которые в нём описаны? Словно
  прошлое хватает нас за горло и заставляет проживать чужую боль и ярость
  заново.
</p>
<p>
  Из примечательного в этой части дневника могу отметить лишь то, что
  Страд боролся против ордена Серебряного дракона и самого Серебряного
  дракона. Надеюсь, нам не придётся сражаться ни с живым, ни с мёртвым
  драконом — мне лично и одного вампира с лихвой хватает.
</p>
<p>
  В любом случае мы успешно пережили ещё один день. И пусть впереди
  наверняка ждут новые испытания, я верю, что мы так же удачно переживём и
  все последующие дни — какими бы сложными они ни были. Завтра будет новый
  день. Я дам обещанный концерт и исполню свою песню — ту самую, что
  родилась из всех этих страхов, надежд и упрямого желания не сдаваться.
  Надеюсь, последствия этого порыва будут исключительно положительными. Не
  хотелось бы разочаровать публику или, того хуже, навлечь на себя гнев
  врагов раньше времени. Но если уж я решилась выйти из тени, то сделаю
  это с высоко поднятой головой — и пусть весь мир видит, что даже бард
  способен быть не просто голосом, а опорой для тех, кто почти потерял
  надежду.
</p>

