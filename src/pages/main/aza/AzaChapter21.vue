<p>
  Ближе к вечеру мы всё же решили заглянуть на праздник святого Андрала в
  церкви. Хорошо, что хватило ума не подписываться на участие в нём на
  целый день. От праздника там осталось одно название — скучнейшее
  мероприятие, достойное разве что того, чтобы навевать сон даже на самых
  стойких. Святоши явно не знают толку в веселье: ни музыки, ни танцев, ни
  хотя бы приличного угощения — сплошные молитвы, чинные поклоны и
  взгляды, которыми они будто пытаются выжечь из гостей любую искру
  непочтительности. Ох, да я бы им показала, как надо устраивать
  праздники… Но сейчас не до того.
</p>
<p>
  Стоило мне уже было поверить, что день нашей передышки складывается
  вполне сносно, как с улицы донёсся шум. А в этих краях шум никогда не
  сулит ничего хорошего — каждый раз он становится предвестником
  опасности, угрожающей самой нашей жизни. Кто бы мог подумать, что я
  доживу до того дня, когда начну скучать по разборкам пьяниц у таверны
  или очередным скандалам изменщиков со своими вторыми половинками! Да,
  эти звуки были неприятны, но они не вынуждали меня рисковать собой,
  обнажать клинок и гадать, выживу ли я до заката.
</p>
<p>
  А тут… На нас вновь напали. На этот раз — шесть порождений вампира. Бой
  выдался настолько выматывающим, что я почти потеряла сознание от
  полученных ран. В какойто миг мир сузился до звона в ушах, тяжести
  арбалета в руках и хриплого дыхания рядом — и всё же обошлось. Мы вновь
  победили.
</p>
<p>
  Осмотрев тела павших тварей, мы столкнулись с неприятным, почти
  леденящим душу фактом: похоже, в прошлой жизни они были такими же
  искателями приключений, как и мы. Жуть берёт при одной мысли об этом. Не
  хочу даже представлять, что подобное может произойти и со мной. И тут
  вопросов становится больше, чем ответов: может, это очередная
  демонстрация власти Страда? Или часть плана по захвату города и
  уничтожению единственного святого места здесь? А может, это была ещё
  одна попытка похитить Ирину? Догадок много, а вот ответ нам сможет дать
  лишь время — и, боюсь, оно не будет особенно щедрым на откровения.
</p>

