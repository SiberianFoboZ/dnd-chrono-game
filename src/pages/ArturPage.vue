          горло и протащил через весь зал, опрокинув его на обеденный стол.
          Первое, что я спросил в порыве ярости: «ГДЕ КОСТИ, КОТОРЫЕ ТЫ ВЫКРАЛ?
          ГОВОРИ НЕМЕДЛЕННО!». Надо сказать, тут Азалия хоть смогла чуть мягче
          выбить из него информацию. Так я узнал, что он продал святую реликвию
          Хендрику ван дер Воорту, местному гробовщику. Я был готов двинуться
          прямо сейчас, вырвать ему руки и после распять на кресте в священном
          пламени, но смог успокоить свою ярость. Мы двинулись к бургомистру,
          чтобы выслушать его просьбу: в обмен на помощь он даст нам разрешение
          на ношение оружия.
        </p>
        <p>
          Я, конечно, знал, что знатные люди любят хвастаться своими
          достижениями. Но когда они говорят, что в одиночку убили медведя, это
          скорее значит, что с ним был еще десяток человек, которые помогли
          загнать его в угол, изрядно ранить, и какой-нибудь дурак не смог
          удержать его лапу, оставив ему глубокую царапину. Но я бы посмотрел,
          как он с легкостью втыкает нож в толстую медвежью шкуру. Туда не
          всегда самый острый клинок можно вогнать, а о ноже я и вовсе молчу. Но
          так мы узнали, что некий Уолт подозревается в убийстве собственной
          мачехи. Сложно было это признать, но после недолгого диалога стало
          понятно: он точно не мог этого сделать. Он слишком невинное дитя,
          которое оказалось в ненужном месте в ненужное время.
        </p>
        <p>
          Мы снова разделились. Теперь я мог вершить правосудие так, как считал
          нужным, и двинулся к дому Хендрика. Старик, жалкий старик. Скорее
          всего, он чья-то пешка, которая за пару монет была готова совершить
          богохульство. И он его совершил. Первым делом я почувствовал в его
          доме жуткий запах скверны и уже было хотел снести ему голову, однако
          меча под рукой не оказалось — только кинжал. Я чувствовал, что кости
          где-то в доме, и даже знал где: на втором этаже. Первым делом я
          потащил старика за шкирку наверх. Бедняга не поспевал за мной, но мой
          гнев было не унять. Мало того что он украл кости, так он еще и держит
          дома нежить или демонов! Я подошел к гробам и начал вскрывать их по
          одному. Все пустые... Значит, они либо в замке Равенлофт, либо на
          охоте. Не стану их ждать, есть другая важная задача. Я крепко сжал
          руку Хендрика и положил ее на крышку гроба. Первый и единственный
          вопрос, от которого он сломался: «ГДЕ СЕЙЧАС КОСТИ? Я ЗНАЮ, ЧТО ОНИ В
          ТВОЕМ ДОМЕ. ЕСЛИ ТЫ ИХ НЕ ОТДАШЬ НЕМЕДЛЕННО, Я ОТРУБЛЮ ТЕБЕ ПАЛЬЦЫ, И
          ТЫ БОЛЬШЕ НИКОГДА НЕ СМОЖЕШЬ ВЗЯТЬ В РУКИ МОЛОТОК». Мне стыдно за это
          содеянное, но времени у нас слишком мало. А после его надо предать
          правосудию и отдать под стражу. Старик раскололся и повел меня в свою
          спальню, откуда вытащил ящик с двойным дном. Конечно, всё было там. Он
          отдал мне кости, а грязные деньги я не стал брать. Люди идут на
          преступления не от хорошей жизни, а чаще из-за того, что им нечего
          есть.
        </p>
        <p>
          Вернувшись в церковь, я отдал кости первосвященнику и попросил всех
          горожан подождать за дверями. Мой голос звучал как гром среди ясного
          неба. Я передал сверток Лукьяну Петровичу, и под моей охраной он
          спрятал его. После я убедился, что везде повешаны новые замки, а ключи
          всегда у первосвященника. Закончив со всеми почестями лику святых,
          двери церкви снова стали открыты для всех. Я провел молитву своей
          Богине и помолился за здравие остальных, поблагодарив спутников.
        </p>
        <div class="entry">
          <div class="entry-date">- пропажа исмарка -</div>
          <div class="entry-title">Исмарк</div>
        </div>
        <p>
          Далее, решив проверить Исмарка, я надеялся застать его в большем
          здравии или хотя бы с более ясным разумом. Но то, что я увидел,
          повергло меня в шок. Открыв ключом его комнату, я вижу порванные
          веревки и пустую кровать. Я спросил преподобного, что случилось, но он
          лишь сказал, что ключ все время был у него на шее и только что был
          отдан мне. Мы с ним осмотрели дверь. Целая, нетронутая, словно открыта
          ключом. Чертов Исмарк... Я помню, как рванул в таверну просить лошадь
          и вопил во все горло: «ИСМАРК!». Взяв коня на постоялом дворе, я
          рванул за ворота. Я гнал его несколько миль, пока не почувствовал на
          себе взгляд волков. Лошадь тоже вела себя беспокойно, явно чувствуя,
          что может случиться что-то плохое, и периодически отказывалась ехать
          вперед. Я не стал испытывать судьбу, развернул лошадь и помчал на
          полном галопе назад. С тяжелым сердцем мне пришлось сообщить Ирине,
          что её брат пропал. Я ожидал чего угодно, но только не такого
          спокойствия. Никогда.
        </p>
        <p>
          Ночь, наверное, была самой тяжелой. Я помню, как дрался с кем-то
          крайне сильным. Я пытался использовать разные тактики, приемы,
          вспоминать наставления, но всё тщетно. Каждый раз всё было одно и то
          же.
        </p>
        <div class="entry">
          <div class="entry-date">- правосудие -</div>
          <div class="entry-title">Расследование убийства. Убийца.</div>
        </div>
        <p>
          Утром я смог точно узнать, как девушки смогли продвинуться в
          расследовании. Они нашли много улик и даже сложили некоторые кусочки
          пазла. Дальше осталось дело за малым — узнать, что же случилось. Всех
          нас пригласили в лавку писца, где мы узнали кое-какую информацию.
          Оказывается, он смог каким-то чудом через «ряженых» достать несколько
          бочек вина для госпожи Фионы Вахтер. Удивительно. При этом, по словам
          самого хозяина таверны, у него со склада регулярно воруют вино, и он
          не имеет идей, кто это мог быть. Что же, пока девушки обсуждали дело,
          они обмолвились о помощнике кузнеца Арвела, который задолжал немного
          денег вистани и не мог с ними расплатиться. Я с «Ряженой» решил пойти
          сразу к нему, выбивать информацию. Скорее всего, именно он и является
          убийцей. Так и было. Он рассказал, что задолжал крупную сумму вистани,
          и они предложили ему небольшую авантюру — выкрасть немного вина со
          склада. Конечно, он взял с собой молот, чтобы на всякий случай
          отмахнуться. И бедная женщина оказалась слишком близко к нему... Он
          слышал, как она задыхалась в агонии с пробитой головой, и ничего не
          сделал. Встал, оцепенел, а после быстро ушел с тем, что успел стащить,
          и отдал вистани. Я помолюсь за её покой, чтобы её душа была спокойна.
        </p>
        <p>
          Я крепко связал руки бедолаге и вместе с оружием и мотивом мы пришли к
          бургомистру, чтобы отдать под суд убийцу. Это было ужасное разрешение
          на ношение оружия в моей жизни, но хоть так. Он раскаялся перед
          содеянным. Надеюсь, его душа не будет сильно страдать.
        </p>
        <p>
          С разрешением я пошел возвращать «Валькирию». Впереди меня ждет ковка.
          Клинок придется ковать в собственной крови, читая молитвы, чтобы
          связать свою душу с лезвием и направлять карающую длань через его
          сталь.
        </p>
      </div>

